import assert from 'node:assert/strict';
import {cleanCompleted,cleanLayout,parseBackup,stepDistance} from '../storage.mjs';
import {simulate,idealAngle} from '../physics.mjs';
import {lessons} from '../lessons.mjs';
assert.deepEqual(cleanCompleted([2,2,23,-1,24,'1',null],24),[2,23]);
const layout={start:{x:100,y:470},targets:[{x:120,y:180,r:24}],enemies:[{x:220,y:330,r:27,weak:{dx:25,dy:0,r:10}}],blocks:[{x:300,y:500,w:40,h:40}]};
const data={app:'shotlab',version:1,completed:[0,18,23],lastLesson:23,layout};
assert.deepEqual(parseBackup(JSON.stringify(data),24).completed,[0,18,23]);
assert.equal(cleanLayout(layout).enemies[0].weak.dx,25);
assert.throws(()=>parseBackup('{invalid',24));
assert.throws(()=>parseBackup(JSON.stringify({...data,app:'other'}),24));
assert.throws(()=>parseBackup(JSON.stringify({...data,layout:{...layout,start:{x:'<img>',y:2}}}),24));
assert.throws(()=>cleanLayout({...layout,enemies:Array(21).fill(layout.enemies[0])}));
assert.throws(()=>cleanLayout({...layout,blocks:[{x:100,y:200,w:-1,h:40}]}));
assert.equal(cleanLayout({...layout,title:'<script>',__proto__:{evil:true}}).title,undefined);
const run=simulate(lessons[2],idealAngle(lessons[2]),2200),first=run.events[0].dist;
assert.equal(run.events[1].dist,first);
assert.equal(stepDistance(run,0,1),first);
assert(stepDistance(run,first,1)>first,'a simultaneous corner contact must not trap stepping');
assert.equal(stepDistance(run,first,-1),0);
assert.equal(stepDistance(run,run.length,1),run.length);
assert.equal(stepDistance(run,0,-1),0);
console.log('PASS: progress round trip, bounded imported geometry, invalid-file rejection, deduplication, contact stepping and simultaneous corner contacts.');
